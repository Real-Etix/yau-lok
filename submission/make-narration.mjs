async function seconds(file) {
  const { stdout } = await run("ffprobe", [
    "-v", "error", "-show_entries", "format=duration",
    "-of", "default=nw=1:nk=1", file,
  ]);
  return parseFloat(stdout.trim());
}

// Where each clip starts in the finished cut, from what is actually on disk.
const files = await readdir(CLIPS);
const order = ["01-home", "02-minibus", "03-taxi", "04-clinic", "05-cct", "06-scan", "07-language"];
const starts = {};
let cursor = 0;
for (const name of order) {
  const hit = files.find((f) => f.startsWith(name) && /\.(mov|mp4|m4v)$/i.test(f));
  if (!hit) {
    console.log(`  (no ${name} — skipping its lines)`);
    continue;
  }
  const d = await seconds(path.join(CLIPS, hit));
  starts[name] = cursor;
  cursor += d;
  console.log(`  ${name.padEnd(12)} starts ${cursor - d < 10 ? " " : ""}${(cursor - d).toFixed(1)}s  runs ${d.toFixed(1)}s`);
}
const TOTAL = cursor + CARD_SECONDS;
console.log(`  ${"08-close".padEnd(12)} starts ${cursor.toFixed(1)}s  runs ${CARD_SECONDS}s`);
console.log(`  total ${Math.floor(TOTAL / 60)}:${String(Math.round(TOTAL % 60)).padStart(2, "0")}\n`);

await rm(WORK, { recursive: true, force: true });
await mkdir(WORK, { recursive: true });

const cues = [];
const placed = [];
for (const [clip, offset, text, zh, subtitle] of SCRIPT) {
  if (starts[clip] === undefined) continue;
  const at = starts[clip] + offset;
  const i = placed.length;
  process.stdout.write(`  ${String(i + 1).padStart(2)} @${at.toFixed(1)}s `);

  const res = await fetch(`${BASE}/api/tts`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ text }),
  });
  if (!res.ok) {
    console.log(`FAILED (${res.status})`);
    console.log("\nTTS is not answering. Record NARRATION.md on your phone instead");
    console.log("and save it as submission/narration.m4a — assemble.sh takes either.");
    process.exit(1);
  }
  const file = path.join(WORK, `${String(i).padStart(2, "0")}.wav`);
  await writeFile(file, Buffer.from(await res.arrayBuffer()));
  const spoken = await seconds(file);
  placed.push({ at, file });
  // The caption stays up for as long as the line is spoken, plus a beat to
  // read the tail of it.
  // 繁體 on top, English under it — the Cantonese is what is being
  // spoken, so it leads.
  cues.push({ from: at, to: at + spoken + 0.6, subtitle: `${zh}\n${subtitle}` });
  console.log(`ok (${spoken.toFixed(1)}s)`);
}

// Trim any cue that would still be on screen when the next line starts.
cues.forEach((c, i) => {
  const next = cues[i + 1];
  if (next && c.to > next.from - 0.15) c.to = next.from - 0.15;
});

const stamp = (s) => {
  const ms = Math.max(0, Math.round(s * 1000));
  const h = String(Math.floor(ms / 3600000)).padStart(2, "0");
  const m = String(Math.floor((ms % 3600000) / 60000)).padStart(2, "0");
  const sec = String(Math.floor((ms % 60000) / 1000)).padStart(2, "0");
  return `${h}:${m}:${sec},${String(ms % 1000).padStart(3, "0")}`;
};

await writeFile(
  path.join(HERE, "narration.srt"),
  cues
    .map((c, i) => `${i + 1}\n${stamp(c.from)} --> ${stamp(c.to)}\n${c.subtitle}\n`)
    .join("\n") + "\n",
  "utf8",
);

// One silent bed the length of the finished cut, every line delayed onto it.
const inputs = placed.flatMap((p) => ["-i", p.file]);
const delays = placed
  .map((p, i) => `[${i + 1}:a]adelay=${Math.round(p.at * 1000)}|${Math.round(p.at * 1000)}[d${i}]`)
  .join(";");
const mix = placed.map((_, i) => `[d${i}]`).join("");

await run("ffmpeg", [
  "-y", "-loglevel", "error",
  "-f", "lavfi", "-t", String(TOTAL), "-i", "anullsrc=channel_layout=stereo:sample_rate=48000",
  ...inputs,
  "-filter_complex",
  `${delays};[0:a]${mix}amix=inputs=${placed.length + 1}:duration=first:normalize=0[a]`,
  "-map", "[a]", "-ar", "48000", "-ac", "2", path.join(HERE, "narration.wav"),
]);

await rm(WORK, { recursive: true, force: true });
console.log(`\n  -> narration.wav + narration.srt (${TOTAL.toFixed(1)}s, ${cues.length} lines)`);
console.log("  now: bash submission/assemble.sh");
