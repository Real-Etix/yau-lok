// Generate the Cantonese narration and its subtitles from HKGAI's own TTS.
//
// Timings are DERIVED from the clips on disk, never assumed. Recording to a
// stopwatch is not a thing anyone does well under deadline, and a narration
// pinned to planned lengths drifts a scenario behind the moment one clip runs
// short. Each line is placed at an offset *inside its own clip*, so re-shoot
// anything, re-run this, and everything lines up again.
//
//   node submission/make-narration.mjs           (dev server on :3001)
//   BASE=https://yau-lok.vercel.app node submission/make-narration.mjs
//
// Writes: submission/narration.wav and submission/narration.srt

import { writeFile, mkdir, rm, readdir } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import path from "node:path";

const run = promisify(execFile);
const BASE = process.env.BASE ?? "http://localhost:3001";
const HERE = path.dirname(new URL(import.meta.url).pathname);
const CLIPS = path.join(HERE, "clips");
const WORK = path.join(HERE, ".narr");

/** The closing card is generated by assemble.sh, so its length is fixed here. */
const CARD_SECONDS = 13;

// [clip, offset into that clip, Cantonese, English subtitle]
const SCRIPT = [
  ["01-home", 1.0, "喺香港，唔識講廣東話，唔係聽唔明，係開唔到口。",
    "In Hong Kong the problem isn't understanding Cantonese —\nit's having to speak it."],

  ["02-minibus", 1.5, "綠色小巴冇按鈴。你要自己嗌「有落」，唔嗌就過咗站。",
    "A green minibus has no bell.\nYou shout 「有落」 — or you miss your stop."],
  ["02-minibus", 20, "有落知道你去邊，夠鐘就幫你嗌出嚟。",
    "Yau Lok knows where you're going,\nand says it out loud for you."],
  ["02-minibus", 44, "落車提示同實時到站，全部嚟自政府嘅小巴數據。",
    "Stop alerts and live arrivals,\nfrom the government's own minibus feed."],

  ["03-taxi", 1.5, "上的士之前就知道大概幾錢，同埋點樣同司機講清楚目的地。",
    "Know the fare before you get in —\nand say the destination clearly."],
  ["03-taxi", 13, "一個真嘅香港咪錶，唔使淨係信個數字。",
    "A real Hong Kong meter, so nobody\nhas to take the number on trust."],

  ["04-clinic", 1.5, "急症室輪候時間係實時嘅，資料直接嚟自醫管局。",
    "A&E waits are live,\nstraight from the Hospital Authority."],
  ["04-clinic", 15, "分流級別同收費，寫得清清楚楚，唔會靠估。",
    "Triage levels and fees, stated plainly —\nnever guessed."],

  ["05-cct", 1.0, "茶餐廳最難嘅唔係啲餸，係伙記寫嗰啲字。",
    "The hard part of a cha chaan teng isn't the food.\nIt's what the waiter writes."],
  ["05-cct", 14, "零T，走冰，少甜。呢個係廚房睇得明嘅寫法，唔係翻譯。",
    "「0T 走冰 少甜」 — the shorthand\nthe kitchen reads, not a translation."],

  ["06-scan", 1.0, "影低塊餐牌，就可以直接落單。",
    "Photograph the menu\nand order straight off it."],
  ["06-scan", 11, "認錯咗？改得。價錢我哋唔會估，睇唔到就問返你。",
    "Misread a line? Fix it. We never invent\na price the camera couldn't read."],

  ["07-language", 1.0, "九種語言，唔係淨係中英文。",
    "Nine languages —\nnot just Chinese and English."],
];

async function seconds(file) {
  const { stdout } = await run("ffprobe", [
    "-v", "error", "-show_entries", "format=duration",
    "-of", "default=nw=1:nk=1", file,
  ]);
  return parseFloat(stdout.trim());
}

// Where each clip starts in the finished cut, from what is actually on disk.
const files = await readdir(CLIPS);
const order = ["01-home", "02-minibus", "03-taxi", "04-clinic", "05-cct", "06-scan", "07-language"];
const starts = {};
let cursor = 0;
for (const name of order) {
  const hit = files.find((f) => f.startsWith(name) && /\.(mov|mp4|m4v)$/i.test(f));
  if (!hit) {
    console.log(`  (no ${name} — skipping its lines)`);
    continue;
  }
  const d = await seconds(path.join(CLIPS, hit));
  starts[name] = cursor;
  cursor += d;
  console.log(`  ${name.padEnd(12)} starts ${cursor - d < 10 ? " " : ""}${(cursor - d).toFixed(1)}s  runs ${d.toFixed(1)}s`);
}
const TOTAL = cursor + CARD_SECONDS;
console.log(`  ${"08-close".padEnd(12)} starts ${cursor.toFixed(1)}s  runs ${CARD_SECONDS}s`);
console.log(`  total ${Math.floor(TOTAL / 60)}:${String(Math.round(TOTAL % 60)).padStart(2, "0")}\n`);

await rm(WORK, { recursive: true, force: true });
await mkdir(WORK, { recursive: true });

const cues = [];
const placed = [];
for (const [clip, offset, text, subtitle] of SCRIPT) {
  if (starts[clip] === undefined) continue;
  const at = starts[clip] + offset;
  const i = placed.length;
  process.stdout.write(`  ${String(i + 1).padStart(2)} @${at.toFixed(1)}s `);

  const res = await fetch(`${BASE}/api/tts`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ text }),
  });
  if (!res.ok) {
    console.log(`FAILED (${res.status})`);
    console.log("\nTTS is not answering. Record NARRATION.md on your phone instead");
    console.log("and save it as submission/narration.m4a — assemble.sh takes either.");
    process.exit(1);
  }
  const file = path.join(WORK, `${String(i).padStart(2, "0")}.wav`);
  await writeFile(file, Buffer.from(await res.arrayBuffer()));
  const spoken = await seconds(file);
  placed.push({ at, file });
  // The caption stays up for as long as the line is spoken, plus a beat to
  // read the tail of it.
  cues.push({ from: at, to: at + spoken + 0.6, subtitle });
  console.log(`ok (${spoken.toFixed(1)}s)`);
}

// Trim any cue that would still be on screen when the next line starts.
cues.forEach((c, i) => {
  const next = cues[i + 1];
  if (next && c.to > next.from - 0.15) c.to = next.from - 0.15;
});

const stamp = (s) => {
  const ms = Math.max(0, Math.round(s * 1000));
  const h = String(Math.floor(ms / 3600000)).padStart(2, "0");
  const m = String(Math.floor((ms % 3600000) / 60000)).padStart(2, "0");
  const sec = String(Math.floor((ms % 60000) / 1000)).padStart(2, "0");
  return `${h}:${m}:${sec},${String(ms % 1000).padStart(3, "0")}`;
};

await writeFile(
  path.join(HERE, "narration.srt"),
  cues
    .map((c, i) => `${i + 1}\n${stamp(c.from)} --> ${stamp(c.to)}\n${c.subtitle}\n`)
    .join("\n") + "\n",
  "utf8",
);

// One silent bed the length of the finished cut, every line delayed onto it.
const inputs = placed.flatMap((p) => ["-i", p.file]);
const delays = placed
  .map((p, i) => `[${i + 1}:a]adelay=${Math.round(p.at * 1000)}|${Math.round(p.at * 1000)}[d${i}]`)
  .join(";");
const mix = placed.map((_, i) => `[d${i}]`).join("");

await run("ffmpeg", [
  "-y", "-loglevel", "error",
  "-f", "lavfi", "-t", String(TOTAL), "-i", "anullsrc=channel_layout=stereo:sample_rate=48000",
  ...inputs,
  "-filter_complex",
  `${delays};[0:a]${mix}amix=inputs=${placed.length + 1}:duration=first:normalize=0[a]`,
  "-map", "[a]", "-ar", "48000", "-ac", "2", path.join(HERE, "narration.wav"),
]);

await rm(WORK, { recursive: true, force: true });
console.log(`\n  -> narration.wav + narration.srt (${TOTAL.toFixed(1)}s, ${cues.length} lines)`);
console.log("  now: bash submission/assemble.sh");
